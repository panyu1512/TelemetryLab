def _key(name: str) -> str:
    """Fold a country name to its lookup key: lowercase ASCII words."""
    s = unicodedata.normalize("NFKD", name)
    s = "".join(c for c in s if not unicodedata.combining(c)).casefold()
    s = re.sub(r"[^a-z0-9]+", " ", s.replace("&", " and ")).strip()
    s = re.sub(r"\bst\b", "saint", s)
    return re.sub(r"^the ", "", s)


_BY_KEY: Final[dict[str, str]] = {
    _key(name): code for code, names in _NAMES.items() for name in names
}


def country_code(flair_name: Any) -> str:
    """ISO alpha-3 code for a ``FlairName``, or ``""`` if it is not a country."""
    return _BY_KEY.get(_key(str(flair_name or "")), "")
